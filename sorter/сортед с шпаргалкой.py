import os  # Импортируем модуль 'os' для взаимодействия с операционной системой (работа с файлами и директориями).
import shutil  # Импортируем модуль 'shutil' для высокоуровневых операций с файлами (например, перемещение).

# Определяем словарь, который сопоставляет названия категорий (будущих папок) с расширениями файлов.
CATEGORIES = {
    "Изображения": [".jpg", ".jpeg", ".png", ".gif", ".webp"],  # Категория для графических файлов.
    "Видео": [".mp4", ".avi", ".mov", ".mkv"],  # Категория для видеофайлов.
    "Документы": [".pdf", ".docx", ".txt", ".xlsx"],  # Категория для текстовых документов и таблиц.
    "Код": [".py", ".js", ".html", ".css"],  # Категория для файлов с исходным кодом.
    "Архивы": [".zip", ".rar", ".7z"],  # Категория для архивных файлов.
    "Музыка": [".mp3", ".flac", ".waw", ".aac", ".ogg"],  # Категория для аудиофайлов.
}


# Функция для определения категории файла по его расширению.
def get_categories(type_file):
    # Перебираем все пары "категория: список_расширений" в словаре CATEGORIES.
    for category, extension in CATEGORIES.items():
        # Если расширение файла (type_file) найдено в текущем списке расширений (extension)...
        if type_file in extension:
            return category  # ...возвращаем название этой категории.
    return "Разное"  # Если расширение не найдено ни в одной из категорий, возвращаем "Разное".


# Функция для сортировки файлов в указанной папке.
def sort_folder(folder_path):
    # Получаем список всех элементов (файлов и папок) в указанной директории.
    for item in os.listdir(folder_path):
        # Формируем полный путь к текущему элементу, используя os.path.join для кроссплатформенности.
        file_path = os.path.join(folder_path, item)

        # Проверяем, является ли текущий элемент файлом.
        if not os.path.isfile(file_path):
            continue  # Если это не файл (т.е. папка), пропускаем его и переходим к следующему элементу.

        # Разделяем имя файла на базовое имя и расширение.
        # _ используется для игнорирования базового имени, так как оно нам здесь не нужно.
        _, ext = os.path.splitext(item)

        # Определяем категорию файла с помощью функции get_categories.
        category = get_categories(ext)

        # Формируем полный путь к целевой папке для этой категории.
        dest_folder = os.path.join(folder_path, category)

        # Создаем целевую папку, если она еще не существует.
        # exist_ok=True предотвращает ошибку, если папка уже есть.
        os.makedirs(dest_folder, exist_ok=True)

        # Перемещаем файл из исходного местоположения в целевую папку.
        shutil.move(file_path, os.path.join(dest_folder, item))

    return "Сортировка завершена"  # Возвращаем сообщение о завершении сортировки.


# Функция для подсчета файлов в созданных папках-категориях.
def count_items(base_folder_path):
    # Получаем список всех элементов (файлов и папок) в базовой папке после сортировки.
    items_in_base_folder = os.listdir(base_folder_path)

    # Перебираем каждый элемент в базовой папке.
    for item_name in items_in_base_folder:
        # Формируем полный путь к текущему элементу.
        item_path = os.path.join(base_folder_path, item_name)

        # Проверяем, является ли текущий элемент папкой.
        # Это позволяет нам обрабатывать только папки-категории, созданные сортировщиком.
        if os.path.isdir(item_path):
            file_count = 0  # Инициализируем счетчик файлов для текущей категории.

            # Итерируем по содержимому этой папки-категории.
            for file_in_category in os.listdir(item_path):
                # Формируем полный путь к элементу внутри папки категории.
                full_file_path = os.path.join(item_path, file_in_category)

                # Проверяем, является ли этот элемент файлом (игнорируем возможные подпапки, если они есть).
                if os.path.isfile(full_file_path):
                    file_count += 1  # Увеличиваем счетчик, если это файл.

            # Выводим результат: название папки-категории и количество файлов в ней.
            print(f"Всего файлов в папке {item_name}: {file_count} шт.")


# --- Основная часть программы ---

# Вызываем функцию сортировки для указанной папки и выводим результат.
print(sort_folder("D:/need_too_sort"))
# Вызываем функцию подсчета файлов для той же папки, чтобы увидеть результаты сортировки.
count_items("D:/need_too_sort")
